# Welcome to the Club!

Here's a riddle for you:

I'm louder than a whisper, softer than a scream.<br>
I live between the shower and the karaoke machine.<br>
You'll find me at parties, in cars, in the rain.<br>
I come out big on Saturdays to kill the weekday pain.

**What am I?**

Answer: Your voice. And we can't wait to hear it!

Mark the last Saturday of the month as your night to party. We'll send a reminder as we get closer to the date. You can always check the website for updates.

